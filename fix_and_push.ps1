#  Written by SWGReturn (Claude), 2026-08-15.
#
#  WHAT WENT WRONG
#  `git add -A` swept in MMOCoreORB/bin/databases -- the runtime Berkeley
#  DB. __db.001 is 628 MB; GitHub's hard limit is 100 MB, so the push was
#  rejected. The commit is LOCAL ONLY; nothing reached GitHub, so a soft
#  reset undoes it cleanly with no history rewrite.
#
#  TWO .gitignore PROBLEMS FOUND
#   1. bin/databases is not ignored  -> the 628 MB upload.
#   2. `*.sh` IS ignored -> patches/apply.sh, the script that keeps the
#      engine3 fix alive across submodule updates, would have been
#      silently left out of the repo. Needs an explicit negation.
#
#  (bin/conf/* is already ignored, so config-local.lua and the database
#   password were never in the commit. Good, given the repo is going public.)
